-- CASEZERO: metadata for files stored in the private Supabase Storage bucket.
-- Run this only if Hibernate has not created the table automatically.

create table if not exists public.investigation_attachments (
    id bigint generated by default as identity primary key,
    draft_id bigint not null references public.investigation_drafts(id) on delete cascade,
    original_filename varchar(255) not null,
    storage_path varchar(700) not null,
    content_type varchar(120) not null,
    file_size bigint not null check (file_size > 0),
    uploaded_at timestamp without time zone not null default now()
);

create index if not exists idx_investigation_attachments_draft_id
    on public.investigation_attachments(draft_id);
