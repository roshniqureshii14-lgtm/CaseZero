-- Run once in Supabase SQL Editor.
-- API results are stored separately from public case_records until reviewed.
CREATE TABLE IF NOT EXISTS public.case_research_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(500) NOT NULL,
    source_name VARCHAR(200),
    source_url VARCHAR(1000) NOT NULL UNIQUE,
    published_at VARCHAR(80),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    collected_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_case_research_reports_status_collected
    ON public.case_research_reports (status, collected_at DESC);
-- Do not expose this private review table through the public Supabase Data API.
