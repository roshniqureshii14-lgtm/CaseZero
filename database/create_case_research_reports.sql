-- Run once in Supabase SQL Editor.
-- External articles remain separate from public case_records until reviewed.
CREATE TABLE IF NOT EXISTS public.case_research_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(500) NOT NULL,
    source_name VARCHAR(200),
    source_url VARCHAR(1000) NOT NULL UNIQUE,
    published_at VARCHAR(80),
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    collected_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Safe for installations where the table was created by the earlier GDELT version.
ALTER TABLE public.case_research_reports ADD COLUMN IF NOT EXISTS description TEXT;
CREATE INDEX IF NOT EXISTS idx_case_research_reports_status_collected
    ON public.case_research_reports (status, collected_at DESC);
ALTER TABLE public.case_research_reports ENABLE ROW LEVEL SECURITY;
-- No anon/authenticated policies are created. The app's existing direct PostgreSQL
-- connection continues to manage this table.