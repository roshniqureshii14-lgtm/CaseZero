-- CASEZERO persistent public case comments.
-- Safe to run more than once in the Supabase SQL Editor.
CREATE TABLE IF NOT EXISTS public.case_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES public.case_records(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    content VARCHAR(1500) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_case_comments_case_created
    ON public.case_comments (case_id, created_at);

-- Keep the column definitions aligned with the JPA entity.
ALTER TABLE public.case_comments
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP;
