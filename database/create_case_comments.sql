-- CASEZERO public case comments
-- Run this only if Hibernate has not created the table automatically.
create table if not exists public.case_comments (
    id bigint generated by default as identity primary key,
    case_id bigint not null references public.case_records(id) on delete cascade,
    user_id bigint not null references public.app_users(id) on delete cascade,
    content varchar(1500) not null,
    created_at timestamp without time zone not null default now()
);
create index if not exists idx_case_comments_case_created
    on public.case_comments(case_id, created_at);
