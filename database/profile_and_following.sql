-- CASEZERO public member profiles and follow relationships
-- Run this once in the Supabase SQL Editor.

ALTER TABLE public.app_users
    ADD COLUMN IF NOT EXISTS bio VARCHAR(300),
    ADD COLUMN IF NOT EXISTS location VARCHAR(100);

-- Existing accounts need public IDs before their profile URLs can be used.
UPDATE public.app_users
SET public_id = 'CZ-' || UPPER(SUBSTRING(REPLACE(gen_random_uuid()::TEXT, '-', '') FROM 1 FOR 8))
WHERE public_id IS NULL OR BTRIM(public_id) = '';

CREATE UNIQUE INDEX IF NOT EXISTS uk_app_users_public_id
    ON public.app_users(public_id);

CREATE TABLE IF NOT EXISTS public.user_follows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    followed_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_follow_pair UNIQUE (follower_id, followed_id),
    CONSTRAINT ck_user_follow_not_self CHECK (follower_id <> followed_id)
);

CREATE INDEX IF NOT EXISTS idx_user_follows_follower
    ON public.user_follows(follower_id);

CREATE INDEX IF NOT EXISTS idx_user_follows_followed
    ON public.user_follows(followed_id);
